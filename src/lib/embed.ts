/**
 * Replaces known placeholders with sample values. The builder never resolves
 * real user or guild data — the bot does that when the script is sent.
 */
export function applySampleValues(text: string): string {
  return text.replace(/\{[a-z_.]+\}/gi, (token) => {
    const match = Object.keys(SAMPLE_VALUES).find(
      (key) => key.toLowerCase() === token.toLowerCase(),
    )
    return match ? SAMPLE_VALUES[match] : token
  })
}

export type ValidationIssue = {
  field: string
  message: string
  severity: 'error' | 'warning'
}

export function isHttpUrl(value: string): boolean {
  try {
    const url = new URL(value)
    return url.protocol === 'http:' || url.protocol === 'https:'
  } catch {
    return false
  }
}

export function validateEmbed(config: EmbedConfig): ValidationIssue[] {
  const issues: ValidationIssue[] = []

  if (config.content.length > EMBED_LIMITS.content) {
    issues.push({
      field: 'content',
      severity: 'error',
      message: `Message content is ${config.content.length} characters (limit ${EMBED_LIMITS.content}).`,
    })
  }
  if (config.title.length > EMBED_LIMITS.title) {
    issues.push({
      field: 'title',
      severity: 'error',
      message: `Title is ${config.title.length} characters (limit ${EMBED_LIMITS.title}).`,
    })
  }
  if (config.description.length > EMBED_LIMITS.description) {
    issues.push({
      field: 'description',
      severity: 'error',
      message: `Description is ${config.description.length} characters (limit ${EMBED_LIMITS.description}).`,
    })
  }
  if (config.authorName.length > EMBED_LIMITS.authorName) {
    issues.push({
      field: 'authorName',
      severity: 'error',
      message: `Author name is ${config.authorName.length} characters (limit ${EMBED_LIMITS.authorName}).`,
    })
  }
  if (config.footerText.length > EMBED_LIMITS.footerText) {
    issues.push({
      field: 'footerText',
      severity: 'error',
      message: `Footer text is ${config.footerText.length} characters (limit ${EMBED_LIMITS.footerText}).`,
    })
  }
  if (config.color && !isHexColor(config.color)) {
    issues.push({ field: 'color', severity: 'error', message: 'Color must be a hex value such as #77A9F7.' })
  }
  if (config.fields.length > EMBED_LIMITS.fieldCount) {
    issues.push({
      field: 'fields',
      severity: 'error',
      message: `An embed supports up to ${EMBED_LIMITS.fieldCount} fields.`,
    })
  }
  config.fields.forEach((field, index) => {
    if (field.name.length > EMBED_LIMITS.fieldName) {
      issues.push({
        field: `fields.${index}.name`,
        severity: 'error',
        message: `Field ${index + 1} name is ${field.name.length} characters (limit ${EMBED_LIMITS.fieldName}).`,
      })
    }
    if (field.value.length > EMBED_LIMITS.fieldValue) {
      issues.push({
        field: `fields.${index}.value`,
        severity: 'error',
        message: `Field ${index + 1} value is ${field.value.length} characters (limit ${EMBED_LIMITS.fieldValue}).`,
      })
    }
    if (!field.name.trim() || !field.value.trim()) {
      issues.push({
        field: `fields.${index}`,
        severity: 'warning',
        message: `Field ${index + 1} is missing a name or a value and will be skipped by Discord.`,
      })
    }
  })
  if (config.buttons.length > EMBED_LIMITS.buttonCount) {
    issues.push({
      field: 'buttons',
      severity: 'error',
      message: `A message supports up to ${EMBED_LIMITS.buttonCount} buttons per row.`,
    })
  }
  config.buttons.forEach((button, index) => {
    if (button.label.length > EMBED_LIMITS.buttonLabel) {
      issues.push({
        field: `buttons.${index}.label`,
        severity: 'error',
        message: `Button ${index + 1} label is ${button.label.length} characters (limit ${EMBED_LIMITS.buttonLabel}).`,
      })
    }
    if (!button.url.trim()) {
      issues.push({
        field: `buttons.${index}.url`,
        severity: 'error',
        message: `Button ${index + 1} needs a URL — the builder only creates link buttons.`,
      })
    } else if (!isHttpUrl(button.url)) {
      issues.push({
        field: `buttons.${index}.url`,
        severity: 'error',
        message: `Button ${index + 1} URL must start with http:// or https://.`,
      })
    }
  })

  for (const [field, value] of [
    ['image', config.image],
    ['thumbnail', config.thumbnail],
    ['authorIcon', config.authorIcon],
    ['footerIcon', config.footerIcon],
    ['authorUrl', config.authorUrl],
  ] as const) {
    if (value.trim() && !isHttpUrl(value)) {
      issues.push({ field, severity: 'error', message: 'Enter a valid http(s) URL.' })
    }
  }

  const total =
    config.title.length +
    config.description.length +
    config.authorName.length +
    config.footerText.length +
    config.fields.reduce((sum, field) => sum + field.name.length + field.value.length, 0)
  if (total > EMBED_LIMITS.totalCharacters) {
    issues.push({
      field: 'total',
      severity: 'error',
      message: `Embed text is ${total} characters (limit ${EMBED_LIMITS.totalCharacters}).`,
    })
  }

  for (const [field, value] of [
    ['content', config.content],
    ['title', config.title],
    ['description', config.description],
    ['authorName', config.authorName],
    ['footerText', config.footerText],
  ] as const) {
    if (value.includes(EMBED_SEPARATOR)) {
      issues.push({
        field,
        severity: 'error',
        message: 'The "$v" separator cannot be used inside a value — it would split the script.',
      })
    }
  }

  return issues
}

/** Values that would break the `$v` / ` && ` separators when serialized. */
export function serializeConflicts(config: EmbedConfig): string[] {
  const conflicts: string[] = []
  const check = (label: string, value: string) => {
    if (value.includes(' && ')) conflicts.push(label)
  }
  check('message content', config.content)
  check('title', config.title)
  check('description', config.description)
  check('author name', config.authorName)
  check('author icon URL', config.authorIcon)
  check('author URL', config.authorUrl)
  check('footer text', config.footerText)
  check('footer icon URL', config.footerIcon)
  check('image URL', config.image)
  check('thumbnail URL', config.thumbnail)
  config.fields.forEach((field, index) => {
    check(`field ${index + 1} name`, field.name)
    check(`field ${index + 1} value`, field.value)
  })
  config.buttons.forEach((button, index) => {
    check(`button ${index + 1} label`, button.label)
    check(`button ${index + 1} emoji`, button.emoji)
    check(`button ${index + 1} URL`, button.url)
  })
  return conflicts
}
