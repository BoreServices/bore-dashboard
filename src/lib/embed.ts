/**
 * Bore embed script format.
 *
 * The bot's parser (base/managers/EmbedBuilder.py) splits a script on `$v`,
 * strips one character from each side of every part (so parts are wrapped in
 * `{}`), and reads `key:value` pairs. Everything in this module mirrors that
 * implementation so scripts produced here run in the bot unchanged.
 */

export const EMBED_MARKER = '{embed}'
export const EMBED_SEPARATOR = '$v'

export type EmbedButtonStyle = 'primary' | 'secondary' | 'success' | 'danger'

export type EmbedButton = {
  id: string
  label: string
  url: string
  emoji: string
  style: EmbedButtonStyle
  disabled: boolean
}

export type EmbedField = {
  id: string
  name: string
  value: string
  inline: boolean
}

export type EmbedConfig = {
  content: string
  title: string
  description: string
  color: string
  image: string
  thumbnail: string
  authorName: string
  authorIcon: string
  authorUrl: string
  footerText: string
  footerIcon: string
  fields: EmbedField[]
  buttons: EmbedButton[]
}

export const EMBED_LIMITS = {
  content: 2000,
  title: 256,
  description: 4096,
  authorName: 256,
  footerText: 2048,
  fieldName: 256,
  fieldValue: 1024,
  fieldCount: 25,
  buttonCount: 5,
  buttonLabel: 80,
  totalCharacters: 6000,
} as const

export function newId(prefix = 'id'): string {
  return `${prefix}-${Math.random().toString(36).slice(2, 9)}`
}

/**
 * Mirrors `EmbedBuilder.get_parts`: the `{embed}` marker is removed from the
 * whole script first, then every `$v` separated part loses its first and last
 * character (the braces).
 */
export function getParts(script: string): string[] {
  return script
    .replaceAll(EMBED_MARKER, '')
    .split(EMBED_SEPARATOR)
    .map((part) => part.slice(1, -1))
}

/** Mirrors `str.replace` semantics used by the Python parser. */
function stripAll(value: string, needle: string): string {
  return value.split(needle).join('')
}

const BOT_STYLE_BY_NAME: Record<EmbedButtonStyle, string> = {
  primary: 'blue',
  secondary: 'gray',
  success: 'green',
  danger: 'red',
}

const STYLE_BY_BOT_NAME: Record<string, EmbedButtonStyle> = {
  blue: 'primary',
  gray: 'secondary',
  grey: 'secondary',
  green: 'success',
  red: 'danger',
}

export function emptyEmbed(): EmbedConfig {
  return {
    content: '',
    title: '',
    description: '',
    color: '#77A9F7',
    image: '',
    thumbnail: '',
    authorName: '',
    authorIcon: '',
    authorUrl: '',
    footerText: '',
    footerIcon: '',
    fields: [],
    buttons: [],
  }
}

