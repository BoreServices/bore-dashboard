export function serializeEmbed(config: EmbedConfig): string {
  const parts: string[] = [EMBED_MARKER]

  if (config.content) parts.push(`{content:${config.content}}`)
  if (config.title) parts.push(`{title:${config.title}}`)
  if (config.description) parts.push(`{description:${config.description}}`)
  if (config.color) parts.push(`{color:${config.color.replace('#', '')}}`)
  if (config.authorName || config.authorIcon || config.authorUrl) {
    parts.push(
      `{author:${[config.authorName, config.authorIcon, config.authorUrl].join(' && ')}}`,
    )
  }
  for (const field of config.fields) {
    parts.push(`{field:${[field.name, field.value, field.inline ? 'true' : 'false'].join(' && ')}}`)
  }
  if (config.footerText || config.footerIcon) {
    parts.push(`{footer:${[config.footerText, config.footerIcon].join(' && ')}}`)
  }
  if (config.image) parts.push(`{image:${config.image}}`)
  if (config.thumbnail) parts.push(`{thumbnail:${config.thumbnail}}`)
  for (const button of config.buttons) {
    const segments: string[] = ['button:']
    // The bot does not trim the label, so no space is added after `label:`.
    if (button.label) segments.push(`label:${button.label}`)
    if (button.emoji) segments.push(`emoji: ${button.emoji}`)
    if (button.url) segments.push(`url: ${button.url}`)
    segments.push(`style: ${BOT_STYLE_BY_NAME[button.style]}`)
    if (button.disabled) segments.push('disabled')
    parts.push(`{${segments.join(' && ')}}`)
  }

  return parts.join(EMBED_SEPARATOR)
}

/**
 * Mirrors the bot's colour handling: `int(value.replace("#", ""), 16)`, with
 * the bot's `#2F3136` fallback when the value cannot be read as hex.
 */
export function parseBotColor(value: string): number | null {
  const cleaned = value
    .trim()
    .replaceAll('#', '')
    .replace(/^\+/, '')
    .replace(/^0[xX]/, '')
  if (!/^[0-9a-fA-F]+$/.test(cleaned) || cleaned.length > 6) return null
  return Number.parseInt(cleaned, 16)
}

export type ParseResult = {
  config: EmbedConfig
  warnings: string[]
}

export function parseEmbed(script: string): ParseResult {
  const config = emptyEmbed()
  const warnings: string[] = []

  for (const part of getParts(script)) {
    if (!part) continue

    if (part.startsWith('content:')) {
      config.content = part.slice('content:'.length)
    } else if (part.startsWith('title:')) {
      config.title = part.slice('title:'.length)
    } else if (part.startsWith('description:')) {
      config.description = part.slice('description:'.length)
    } else if (part.startsWith('color:')) {
      const raw = part.slice('color:'.length)
      const parsed = parseBotColor(raw)
      if (parsed === null) {
        config.color = '#2F3136'
        warnings.push(`Invalid color "${raw}" — the bot falls back to #2F3136.`)
      } else {
        config.color = `#${parsed.toString(16).padStart(6, '0').toUpperCase()}`
      }
    } else if (part.startsWith('image:')) {
      config.image = part.slice('image:'.length)
    } else if (part.startsWith('thumbnail:')) {
      config.thumbnail = part.slice('thumbnail:'.length)
    } else if (part.startsWith('author:')) {
      const [name, icon, url] = part.slice('author:'.length).split(' && ')
      config.authorName = name || ''
      config.authorIcon = icon || ''
      config.authorUrl = url || ''
    } else if (part.startsWith('field:')) {
      const [name, value, inline] = part.slice('field:'.length).split(' && ')
      config.fields.push({
        id: newId('field'),
        name: name ?? '',
        value: value ?? '',
        inline: inline !== 'false',
      })
    } else if (part.startsWith('footer:')) {
      const [text, icon] = part.slice('footer:'.length).split(' && ')
      config.footerText = text || ''
      config.footerIcon = icon || ''
    } else if (part.startsWith('button:')) {
      const segments = part.slice('button:'.length).split(' && ')
      let label = ''
      let url = ''
      let emoji = ''
      let style: EmbedButtonStyle = 'secondary'
      let disabled = true
      for (const segment of segments) {
        if (segment.includes('label:')) label = stripAll(segment, 'label:').trim()
        if (segment.includes('url:')) {
          url = stripAll(segment, 'url:').trim()
          disabled = false
        }
        if (segment.includes('emoji:')) emoji = stripAll(segment, 'emoji:').trim()
        if (segment.includes('disabled')) disabled = true
        if (segment.includes('style:')) {
          const name = stripAll(segment, 'style:').trim().toLowerCase()
          style = STYLE_BY_BOT_NAME[name] ?? 'secondary'
        }
      }
      // The bot's own `embedcode` command emits `button: label: X`, which its
      // parser reads back with a leading space in the label.
      config.buttons.push({ id: newId('button'), label, url, emoji, style, disabled })
    } else if (part.trim() && part !== EMBED_MARKER) {
      warnings.push(`Ignored unsupported part: ${part.slice(0, 40)}`)
    }
  }

  return { config, warnings }
}

export function isHexColor(value: string): boolean {
  return /^#?([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/.test(value.trim())
}

export function normalizeColor(value: string): string {
  const trimmed = value.trim().replace('#', '')
  if (/^[0-9a-fA-F]{3}$/.test(trimmed)) {
    return `#${trimmed
      .split('')
      .map((char) => char + char)
      .join('')
      .toUpperCase()}`
  }
  if (/^[0-9a-fA-F]{6}$/.test(trimmed)) return `#${trimmed.toUpperCase()}`
  return value
}

export function colorToInt(color: string): number {
  const parsed = Number.parseInt(color.replace('#', ''), 16)
  return Number.isNaN(parsed) ? 0x2f3136 : parsed
}

export type DiscordEmbedJson = {
  title?: string
  description?: string
  color?: number
  author?: { name?: string; icon_url?: string; url?: string }
  footer?: { text?: string; icon_url?: string }
  image?: { url: string }
  thumbnail?: { url: string }
  fields: { name: string; value: string; inline: boolean }[]
}

export type DiscordButtonJson = {
  type: 2
  style: 1 | 2 | 3 | 4
  label?: string
  emoji?: string
  url?: string
  disabled?: boolean
}

export function toDiscordJson(config: EmbedConfig): {
  content: string
  embeds: DiscordEmbedJson[]
  components: { type: 1; components: DiscordButtonJson[] }[]
} {
  const embed: DiscordEmbedJson = { fields: [] }

  if (config.title) embed.title = config.title
  if (config.description) embed.description = config.description
  if (config.color) embed.color = colorToInt(config.color)
  if (config.authorName || config.authorIcon || config.authorUrl) {
    embed.author = {}
    if (config.authorName) embed.author.name = config.authorName
    if (config.authorIcon) embed.author.icon_url = config.authorIcon
    if (config.authorUrl) embed.author.url = config.authorUrl
  }
  if (config.footerText || config.footerIcon) {
    embed.footer = {}
    if (config.footerText) embed.footer.text = config.footerText
    if (config.footerIcon) embed.footer.icon_url = config.footerIcon
  }
  if (config.image) embed.image = { url: config.image }
  if (config.thumbnail) embed.thumbnail = { url: config.thumbnail }
  embed.fields = config.fields.map((field) => ({
    name: field.name,
    value: field.value,
    inline: field.inline,
  }))

  const styleValue: Record<EmbedButtonStyle, 1 | 2 | 3 | 4> = {
    primary: 1,
    secondary: 2,
    success: 3,
    danger: 4,
  }

  return {
    content: config.content,
    embeds: Object.keys(embed).length > 1 || embed.fields.length > 0 ? [embed] : [],
    components: config.buttons.length
      ? [
          {
            type: 1,
            components: config.buttons.map((button) => ({
              type: 2 as const,
              style: styleValue[button.style],
              ...(button.label ? { label: button.label } : {}),
              ...(button.emoji ? { emoji: button.emoji } : {}),
              ...(button.url ? { url: button.url } : {}),
              ...(button.disabled ? { disabled: true } : {}),
            })),
          },
        ]
      : [],
  }
}

